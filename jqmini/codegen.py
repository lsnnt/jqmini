import json
from .ast import BinaryExpr,UnaryExpr,Comparison,Literal
class PythonCodeGenerator:
    def generate(self,ir):
        s=["# Generated by JQMini","def _cmp(row,field,op,value):","    x=row.get(field)","    try:",
           "        if op=='=': return x==value","        if op=='!=': return x!=value",
           "        if op=='>': return x is not None and x>value","        if op=='>=': return x is not None and x>=value",
           "        if op=='<': return x is not None and x<value","        if op=='<=': return x is not None and x<=value",
           "    except TypeError: return False","    return False","","def _where(row):"]
        s.append("    return True" if ir.predicate is None else "    return "+self.e(ir.predicate))
        s+=["","def run(data):","    rows=[r for r in data if _where(r)]"]
        if ir.sort_field:
            f=json.dumps(ir.sort_field)
            s.append(f"    rows.sort(key=lambda r:(r.get({f}) is None,r.get({f})), reverse={ir.sort_desc})")
        if ir.limit is not None:s.append(f"    rows=rows[:{ir.limit}]")
        fs=",".join(repr(x) for x in ir.fields)
        s.append(f"    return [{{k:r.get(k) for k in [{fs}]}} for r in rows]")
        return "\n".join(s)+"\n"
    def e(self,n):
        if isinstance(n,Comparison): return f"_cmp(row,{n.field!r},{n.op!r},{n.value!r})"
        if isinstance(n,BinaryExpr): return f"({self.e(n.left)} {'and' if n.op=='AND' else 'or'} {self.e(n.right)})"
        if isinstance(n,UnaryExpr): return f"(not {self.e(n.operand)})"
        if isinstance(n,Literal): return repr(n.value)
        raise TypeError(type(n))
